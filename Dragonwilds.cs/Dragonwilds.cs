        // How long Stop waits for the world to save before WindowsGSM kills the process
        private const int StopTimeoutMs = 60000;


        // - Create a default cfg for the game server after installation
        public void CreateServerCFG()
        {
            if (File.Exists(ConfigPath))
            {
                return;
            }

            // Same layout as the file the server generates on first launch
            Directory.CreateDirectory(Path.GetDirectoryName(ConfigPath));
            File.WriteAllLines(ConfigPath, new[] { "[SectionsToSave]", "bCanSaveAllSections=true", "" }, new UTF8Encoding(false));
            WriteConfigValues(new Dictionary<string, string>
            {
                { "OwnerId", Placeholder },
                { "ServerName", _serverData.ServerName },
                { "DefaultWorldName", _serverData.ServerMap },
                { "AdminPassword", Placeholder },
                { "WorldPassword", "" },
                { "PlatformPolicy", "Crossplay" }
            });
        }

        // - Start server function, return its Process to WindowsGSM
        public async Task<Process> Start()
        {
            string exePath = ServerPath.GetServersServerFiles(_serverData.ServerID, StartPath);
            if (!File.Exists(exePath))
            {
                exePath = ServerPath.GetServersServerFiles(_serverData.ServerID, LauncherPath);
                if (!File.Exists(exePath))
                {
                    Error = $"{Path.GetFileName(StartPath)} not found ({ServerPath.GetServersServerFiles(_serverData.ServerID, StartPath)})";
                    return null;
                }
                Notice = $"{Path.GetFileName(StartPath)} not found, started {LauncherPath} instead";
            }

            if (!PrepareConfig())
            {
                return null;
            }

            int maxPlayers;
            if (!int.TryParse(_serverData.ServerMaxPlayer, out maxPlayers) || maxPlayers < 1 || maxPlayers > MaxPlayerLimit)
            {
                maxPlayers = MaxPlayerLimit;
                string message = $"Max Players must be 1-{MaxPlayerLimit} for Dragonwilds, using {MaxPlayerLimit}";
                Notice = string.IsNullOrEmpty(Notice) ? message : $"{Notice}. {message}";
            }

            var param = new StringBuilder();
            param.Append($"-Port={_serverData.ServerPort} ");
            param.Append($"-ini:Game:[/Script/Engine.GameSession]:MaxPlayers={maxPlayers} ");
            param.Append(_serverData.ServerParam);

            // Prepare Process
            var p = new Process
            {
                StartInfo =
                {
                    WorkingDirectory = ServerPath.GetServersServerFiles(_serverData.ServerID),
                    FileName = exePath,
                    Arguments = param.ToString().Trim(),
                    // Keep a real console window so WindowsGSM can obtain and later toggle
                    // the MainWindowHandle. WindowsGSM will hide it after startup.
                    WindowStyle = ProcessWindowStyle.Minimized,
                    UseShellExecute = false
                },
                EnableRaisingEvents = true
            };

            // Set up Redirect Input and Output to WindowsGSM Console if EmbedConsole is on.
            // WindowsGSM sets AllowsEmbedConsole to the server's Embed Console toggle before Start.
            if (AllowsEmbedConsole)
            {
                p.StartInfo.CreateNoWindow = true;
                p.StartInfo.RedirectStandardInput = true;
                p.StartInfo.RedirectStandardOutput = true;
                p.StartInfo.RedirectStandardError = true;
                var serverConsole = new ServerConsole(_serverData.ServerID);
                p.OutputDataReceived += serverConsole.AddOutput;
                p.ErrorDataReceived += serverConsole.AddOutput;
            }

            // Start Process
            try
            {
                p.Start();
                if (AllowsEmbedConsole)
                {
                    p.BeginOutputReadLine();
                    p.BeginErrorReadLine();
                }
                else
                {
                    // MainWindowHandle is cached by Process. Refresh while the server creates
                    // its console window so WindowsGSM does not wait forever on a stale zero.
                    for (int i = 0; i < 100 && !p.HasExited; i++)
                    {
                        p.Refresh();
                        if (p.MainWindowHandle != IntPtr.Zero)
                        {
                            break;
                        }

                        await Task.Delay(100);
                    }

                    p.Refresh();
                    if (!p.HasExited && p.MainWindowHandle == IntPtr.Zero)
                    {
                        p.StartInfo.CreateNoWindow = true;
                        Notice = "Dragonwilds started without a usable console window. Toggle Console is unavailable for this session.";
                    }
                }

                return p;
            }
            catch (Exception e)
            {
                Error = e.Message;
                return null; // return null if fail to start
            }
        }

        // - Stop server function
        public async Task Stop(Process p)
        {
            if (p == null || p.HasExited)
            {
                return;
            }

            // Ctrl+C lets the server save the world before exiting
            bool signalled = await Task.Run(() => ConsoleSignal.SendCtrlC(p));
            if (!signalled)
            {
                p.Refresh();
                IntPtr hWnd = p.MainWindowHandle;
                if (hWnd != IntPtr.Zero)
                {
                    await Task.Run(() =>
                    {
                        ServerConsole.SetMainWindow(hWnd);
                        ServerConsole.SendWaitToMainWindow("^c");
                    });
                    signalled = true;
                }
            }

            if (!signalled)
            {
                Notice = "Could not send Ctrl+C to the server; WindowsGSM fallback stop will be used.";
                return;
            }

            // WindowsGSM only waits 10 seconds after Stop returns, so wait for the save here
            await Task.Run(() => p.WaitForExit(StopTimeoutMs));
        }

        // - Update server function
        public new async Task<Process> Update(bool validate = false, string custom = null)
        {
            var (p, error) = await Installer.SteamCMD.UpdateEx(_serverData.ServerID, AppId, validate, custom: custom, loginAnonymous: loginAnonymous);
            Error = error;
            return p;
        }

        public new bool IsInstallValid()
        {
            return File.Exists(ServerPath.GetServersServerFiles(_serverData.ServerID, StartPath))
                || File.Exists(ServerPath.GetServersServerFiles(_serverData.ServerID, LauncherPath));
        }

        public new bool IsImportValid(string path)
        {
            string exePath = Path.Combine(path, StartPath);
            Error = $"Invalid Path! Fail to find {Path.GetFileName(exePath)}";
            return File.Exists(exePath) || File.Exists(Path.Combine(path, LauncherPath));
        }

        public new string GetLocalBuild()
        {
            var steamCMD = new Installer.SteamCMD();
            return steamCMD.GetLocalBuild(_serverData.ServerID, AppId);
        }

        public new async Task<string> GetRemoteBuild()
        {
            var steamCMD = new Installer.SteamCMD();
            return await steamCMD.GetRemoteBuild(AppId);
