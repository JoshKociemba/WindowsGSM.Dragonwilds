        #region DedicatedServer.ini handling
        // Copies the WindowsGSM server name and world name into the ini and checks the required values.
        // The server must be stopped while the ini changes, which is always true here.
        private bool PrepareConfig()
        {
            try
            {
                if (!File.Exists(ConfigPath))
                {
                    CreateServerCFG();
                }

                if (string.IsNullOrWhiteSpace(_serverData.ServerName) || string.IsNullOrWhiteSpace(_serverData.ServerMap))
                {
                    Error = "Server Name and Default Map (the world name) must not be empty";
                    return false;
                }

                // Hosting docs list these limits; the game's own guide doesn't, so only warn
                if (_serverData.ServerName.Length > ServerNameMaxLength || _serverData.ServerMap.Length > WorldNameMaxLength)
                {
                    string message = $"Server Name over {ServerNameMaxLength} or Default Map over {WorldNameMaxLength} characters may be cut off in game";
                    Notice = string.IsNullOrEmpty(Notice) ? message : $"{Notice}. {message}";
                }

                WriteConfigValues(new Dictionary<string, string>
                {
                    { "ServerName", _serverData.ServerName },
                    { "DefaultWorldName", _serverData.ServerMap }
                });

                var values = ReadConfigValues();
                string ownerId, adminPassword, worldPassword, platformPolicy;
                values.TryGetValue("OwnerId", out ownerId);
                values.TryGetValue("AdminPassword", out adminPassword);
                values.TryGetValue("WorldPassword", out worldPassword);
                values.TryGetValue("PlatformPolicy", out platformPolicy);

                if (string.IsNullOrWhiteSpace(ownerId) || ownerId == Placeholder)
                {
                    Error = $"Set OwnerId in {ConfigPath} to your Player ID (bottom of the in-game Settings menu)";
                    return false;
                }

                // The placeholder is a known password, so never start with it
                if (adminPassword == Placeholder)
                {
                    Error = $"Set AdminPassword in {ConfigPath}, or remove the line to run without admins";
                    return false;
                }

                // The server removes this line every time it starts, so keep a copy and put it back before each launch
                if (!string.IsNullOrWhiteSpace(adminPassword))
                {
                    File.WriteAllText(AdminPasswordPath, adminPassword, new UTF8Encoding(false));
                }
                else if (File.Exists(AdminPasswordPath) && !string.IsNullOrWhiteSpace(File.ReadAllText(AdminPasswordPath)))
                {
                    adminPassword = File.ReadAllText(AdminPasswordPath).Trim();
                    WriteConfigValues(new Dictionary<string, string> { { "AdminPassword", adminPassword } });
                }
                else
                {
                    string message = "No AdminPassword set, so nobody but the owner can open Server Management in game";
                    Notice = string.IsNullOrEmpty(Notice) ? message : $"{Notice}. {message}";
                }

                if (!string.IsNullOrEmpty(worldPassword) && !worldPassword.All(char.IsLetterOrDigit))
                {
                    Error = $"WorldPassword in {ConfigPath} may only contain letters and numbers";
                    return false;
                }

                // An unset PlatformPolicy means Crossplay
                if (!string.IsNullOrEmpty(platformPolicy) && !PlatformPolicies.Contains(platformPolicy, StringComparer.OrdinalIgnoreCase))
                {
                    Error = $"PlatformPolicy in {ConfigPath} must be one of: {string.Join(", ", PlatformPolicies)}";
                    return false;
                }

                return true;
            }
            catch (Exception e)
            {
                Error = $"Failed to prepare {ConfigPath}: {e.Message}";
                return false;
            }
        }

        private Dictionary<string, string> ReadConfigValues()
        {
            var values = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            bool inSection = false;
            foreach (string rawLine in File.ReadAllLines(ConfigPath))
            {
                string line = rawLine.Trim();
                if (line.StartsWith("["))
                {
                    inSection = string.Equals(line, ConfigSection, StringComparison.OrdinalIgnoreCase);
                    continue;
                }

                int separator = line.IndexOf('=');
                if (inSection && separator > 0)
                {
                    values[line.Substring(0, separator).Trim()] = line.Substring(separator + 1).Trim();
                }
            }
            return values;
        }

        // Sets keys in the settings section, keeping every other line (ServerGuid etc.) untouched
        private void WriteConfigValues(Dictionary<string, string> updates)
        {
            var lines = File.Exists(ConfigPath) ? File.ReadAllLines(ConfigPath).ToList() : new List<string>();
            var pending = new Dictionary<string, string>(updates, StringComparer.OrdinalIgnoreCase);

            int sectionStart = lines.FindIndex(l => string.Equals(l.Trim(), ConfigSection, StringComparison.OrdinalIgnoreCase));
            if (sectionStart < 0)
            {
                if (lines.Count > 0 && lines[lines.Count - 1].Trim().Length > 0)
                {
                    lines.Add("");
                }
                lines.Add(ConfigSection);
                sectionStart = lines.Count - 1;
            }

            int sectionEnd = sectionStart + 1;
            while (sectionEnd < lines.Count && !lines[sectionEnd].Trim().StartsWith("["))
            {
                int separator = lines[sectionEnd].IndexOf('=');
                if (separator > 0)
                {
                    string key = lines[sectionEnd].Substring(0, separator).Trim();
                    string value;
                    if (pending.TryGetValue(key, out value))
                    {
                        lines[sectionEnd] = $"{key}={value}";
                        pending.Remove(key);
                    }
                }
                sectionEnd++;
            }

            // Insert new keys after the last non-blank line of the section
            int insertAt = sectionEnd;
            while (insertAt > sectionStart + 1 && lines[insertAt - 1].Trim().Length == 0)
            {
                insertAt--;
            }
            foreach (var key in updates.Keys.Where(k => pending.ContainsKey(k)))
            {
                lines.Insert(insertAt++, $"{key}={pending[key]}");
            }

            File.WriteAllLines(ConfigPath, lines, new UTF8Encoding(false));
        }
        #endregion

        // Delivers Ctrl+C to a console process, the same as pressing it in the server window.
        // Works whether the console is visible or hidden by Embed Console.
        private static class ConsoleSignal
        {
            private const uint CtrlCEvent = 0;
            private const uint AllAttachedProcesses = 0;

            [DllImport("kernel32.dll", SetLastError = true)]
            private static extern bool AttachConsole(uint processId);

            [DllImport("kernel32.dll", SetLastError = true)]
            private static extern bool FreeConsole();

            [DllImport("kernel32.dll", SetLastError = true)]
            private static extern bool SetConsoleCtrlHandler(IntPtr handler, bool add);

            [DllImport("kernel32.dll", SetLastError = true)]
            private static extern bool GenerateConsoleCtrlEvent(uint ctrlEvent, uint processGroupId);

            public static bool SendCtrlC(Process process)
            {
                if (!AttachConsole((uint)process.Id))
                {
                    return false;
                }

                // A null handler makes WindowsGSM ignore the signal it is about to raise on the shared console
                SetConsoleCtrlHandler(IntPtr.Zero, true);
                try
                {
                    bool sent = GenerateConsoleCtrlEvent(CtrlCEvent, AllAttachedProcesses);

                    // The signal is handled asynchronously, so stay attached long enough for it to arrive
                    if (sent)
                    {
                        process.WaitForExit(2000);
                    }
                    return sent;
                }
                finally
                {
                    FreeConsole();
                    SetConsoleCtrlHandler(IntPtr.Zero, false);
                }
            }
        }
