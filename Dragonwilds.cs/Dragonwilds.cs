        private const int MaxPlayerLimit = 6;
        private const int ServerNameMaxLength = 32;
        private const int WorldNameMaxLength = 20;
        private static readonly string[] PlatformPolicies = { "Crossplay", "PC", "PlayStation", "Xbox", "Nintendo" };
